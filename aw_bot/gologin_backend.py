class GoLoginError(AwBotError):
    pass


def fetch_profiles(token: str) -> list[dict]:
    gl = GoLogin({"token": token, "profile_id": None})
    payload = gl.profiles()
    if isinstance(payload, dict):
        return payload.get("profiles", []) or []
    return payload or []


def list_profiles(token: str) -> int:
    profiles = fetch_profiles(token)
    if not profiles:
        print("No profiles on this account (or the token lacks access to them).")
        return 1

    print(f"{len(profiles)} profile(s):\n")
    for profile in profiles:
        proxy = profile.get("proxy") or {}
        where = proxy.get("host") or proxy.get("mode") or "no proxy"
        print(f"  {profile.get('id')}  {profile.get('name', '<unnamed>')}")
        print(f"      os={profile.get('os', '?')}  proxy={where}")
    print("\nPut the ID you want in .env as GOLOGIN_PROFILE_ID.")
    return 0


DISPOSABLE_PREFIX = "aw-"


def _is_disposable(profile: dict) -> bool:
    return str(profile.get("name") or "").startswith(DISPOSABLE_PREFIX)


def count_profiles(token: str) -> tuple[int, int]:
    try:
        profiles = fetch_profiles(token)
    except Exception as exc:
        LOG.debug("Could not count profiles: %s", exc)
        return 0, 0
    return len(profiles), sum(1 for p in profiles if _is_disposable(p))


def cleanup_disposable_profiles(token: str, dry_run: bool = False) -> int:
    try:
        profiles = fetch_profiles(token)
    except Exception as exc:
        raise GoLoginError(f"Could not list profiles: {exc}") from exc

    leftovers = [p for p in profiles if _is_disposable(p)]
    kept = len(profiles) - len(leftovers)

    if not leftovers:
        LOG.info(
            "No leftover profiles to remove (%d profile(s) on the account, "
            "none of them generated by this project).", len(profiles),
        )
        return 0

    LOG.info(
        "%d leftover profile(s) to remove; %d other profile(s) will be left "
        "alone.", len(leftovers), kept,
    )
    if dry_run:
        for profile in leftovers:
            LOG.info("  would delete %s  %s", profile.get("id"), profile.get("name"))
        return 0

    removed = 0
    for profile in leftovers:
        profile_id = profile.get("id")
        if not profile_id:
            continue
        if delete_profile(token, profile_id):
            removed += 1
    LOG.info("Removed %d leftover profile(s).", removed)
    return removed


class ProfilePool:
    def __init__(self, token: str, profile_ids: list[str]) -> None:
        if not profile_ids:
            raise GoLoginError(
                "No GoLogin profiles to run. Set GOLOGIN_PROFILE_ID in .env, pass "
                "--gologin-profile, or use --random-profile to draw from the account."
            )
        self.token = token
        self.all_ids = list(profile_ids)
        self._free = list(profile_ids)
        self._condition = threading.Condition()

    def __len__(self) -> int:
        return len(self.all_ids)

    @contextmanager
    def lease(self, release: bool = True):
        with self._condition:
            while not self._free:
                LOG.info("All %d GoLogin profile(s) busy; waiting for one", len(self.all_ids))
                self._condition.wait()
            profile_id = self._free.pop(random.randrange(len(self._free)))
        try:
            yield profile_id
        finally:
            if release:
                with self._condition:
                    self._free.append(profile_id)
                    self._condition.notify()


def resolve_profile_ids(cfg: RunConfig) -> list[str]:
    gl_cfg = cfg.gologin
    if gl_cfg.random_profile or not gl_cfg.profile_ids:
        ids = [p["id"] for p in fetch_profiles(gl_cfg.token) if p.get("id")]
        if not ids:
            raise GoLoginError(
                "This account has no profiles (or the token cannot see them). "
                "Create one at app.gologin.com first."
            )
        LOG.info("Drawing from all %d profile(s) on the account", len(ids))
        return ids
    return list(gl_cfg.profile_ids)


def create_disposable_profile(cfg: RunConfig, worker_id: int = 1) -> tuple[str, str]:
    gl_cfg = cfg.gologin
    gl = GoLogin({"token": gl_cfg.token, "profile_id": None})

    os_choice = _pick_os(gl_cfg.profile_os)
    name = f"aw-{worker_id}-{random.randint(100000, 999999)}"

    try:
        created = gl.createProfileRandomFingerprint({"os": os_choice, "name": name})
    except Exception as exc:
        raise GoLoginError(f"Could not create a GoLogin profile: {exc}") from exc

    profile_id = _created_id(created)
    if not profile_id:
        raise GoLoginError(f"GoLogin did not return a profile id (got {created!r})")

    LOG.info("[w%d] Created profile %s (%s, os=%s)", worker_id, profile_id, name, os_choice)

    if gl_cfg.freshen_user_agent:
        _freshen_user_agent(gl, profile_id, worker_id)

    try:
        gl.addGologinProxyToProfile(
            profile_id, gl_cfg.proxy_country, gl_cfg.proxy_type or ""
        )
        LOG.info(
            "[w%d] Attached a %s %s proxy",
            worker_id, gl_cfg.proxy_country, gl_cfg.proxy_type or "auto-selected",
        )
    except Exception as exc:
        delete_profile(gl_cfg.token, profile_id, worker_id)
        raise GoLoginError(
            f"Could not attach a proxy to the new profile ({exc}). "
            f"Check the account's {gl_cfg.proxy_type or 'proxy'} traffic balance."
        ) from exc

    _match_profile_to_proxy(gl, profile_id, worker_id)

    return profile_id, f"{name} ({os_choice})"


_OS_WEIGHTS = {"win": 78, "mac": 18, "lin": 4}


def _pick_os(allowed) -> str:
    options = tuple(allowed or ("win",))
    weights = [_OS_WEIGHTS.get(name, 1) for name in options]
    return random.choices(options, weights=weights, k=1)[0]


def _freshen_user_agent(gl, profile_id: str, worker_id: int) -> None:
    try:
        gl.updateUserAgentToLatestBrowser([profile_id])
        LOG.info("[w%d] User agent matched to the current browser build", worker_id)
    except Exception as exc:
        LOG.warning(
            "[w%d] Could not update the profile's user agent (%s). The profile "
            "still works; its UA may name an older Chrome than Orbita runs.",
            worker_id, exc,
        )


def _match_profile_to_proxy(gl, profile_id: str, worker_id: int) -> None:
    try:
        gl.setProfileId(profile_id)
        profile = gl.getProfile(profile_id) or {}
    except Exception as exc:
        LOG.debug("[w%d] Could not read the new profile back: %s", worker_id, exc)
        return

    changes: dict = {}

    webrtc = dict(profile.get("webRTC") or {})
    if webrtc.get("mode") == "real" or webrtc.get("fillBasedOnIp") is False:
        webrtc["mode"] = "alerted"
        webrtc["fillBasedOnIp"] = True
        changes["webRTC"] = webrtc

    timezone = dict(profile.get("timezone") or {})
    if timezone.get("fillBasedOnIp") is False:
        timezone["fillBasedOnIp"] = True
        changes["timezone"] = timezone

    if not changes:
        LOG.debug("[w%d] Profile already agrees with its proxy", worker_id)
        return

    try:
        gl.update({"id": profile_id, **changes})
        LOG.info(
            "[w%d] Pointed %s at the proxy exit", worker_id, ", ".join(changes)
        )
    except Exception as exc:
        LOG.warning(
            "[w%d] Could not align the profile with its proxy (%s): %s",
            worker_id, ", ".join(changes), exc,
        )


def _created_id(created) -> str:
    if isinstance(created, str):
        return created
    if isinstance(created, dict):
        for key in ("id", "_id", "profileId", "browserId"):
            value = created.get(key)
            if value:
                return str(value)
    return ""


def delete_profile(token: str, profile_id: str, worker_id: int = 1) -> bool:
    try:
        GoLogin({"token": token, "profile_id": profile_id}).delete(profile_id)
        LOG.info("[w%d] Deleted profile %s", worker_id, profile_id)
        return True
    except Exception as exc:
        LOG.warning(
            "[w%d] Could not delete profile %s: %s -- remove it at app.gologin.com",
            worker_id, profile_id, exc,
        )
        return False


_driver_cache: dict[str, str | None] = {}
_driver_lock = threading.Lock()


def _latest_driver_for_major(major: str) -> str | None:
    try:
        response = requests.get(CFT_LATEST_RELEASE.format(major=major), timeout=20)
        response.raise_for_status()
    except requests.RequestException as exc:
        LOG.warning("Could not look up a chromedriver for Chrome %s: %s", major, exc)
        return None

    version = response.text.strip()
    if not version.startswith(f"{major}.") or len(version.split(".")) != 4:
        return None
    return version


def resolve_chromedriver(chromium_version: str, explicit: str = "") -> str | None:
    if explicit:
        return explicit

    major = (chromium_version or "").split(".")[0]
    if not major.isdigit():
        LOG.warning("Could not read Orbita's version; falling back to Selenium Manager")
        return None

    with _driver_lock:
        if major in _driver_cache:
            return _driver_cache[major]

        path = None
        exact = _latest_driver_for_major(major)
        if exact is None:
            LOG.warning("No chromedriver published for Chrome %s; trying Selenium Manager", major)
        else:
            try:
                from webdriver_manager.chrome import ChromeDriverManager

                path = ChromeDriverManager(driver_version=exact).install()
            except Exception as exc:
                LOG.warning("webdriver-manager could not fetch chromedriver %s: %s", exact, exc)

        _driver_cache[major] = path
        return path


def attach_driver(debugger_address: str, driver_path: str | None, cfg: RunConfig):
    options = Options()
    options.add_experimental_option("debuggerAddress", debugger_address)

    options.page_load_strategy = "eager"

    if getattr(cfg, "capture_browser_logs", False):
        LOG.warning(
            "Browser/network logging is on. It enables the CDP Runtime and "
            "Network domains, which anti-bot scoring can detect -- use it to "
            "diagnose, not for production runs."
        )
        options.set_capability(
            "goog:loggingPrefs", {"browser": "ALL", "performance": "ALL"}
        )

    if driver_path:
        driver = webdriver.Chrome(service=Service(driver_path), options=options)
    else:
        driver = webdriver.Chrome(options=options)

    driver.set_page_load_timeout(cfg.page_timeout)
    return driver


@contextmanager
def gologin_session(cfg: RunConfig, profile_id: str, worker_id: int = 1):
    gl_cfg = cfg.gologin
    extra = list(gl_cfg.extra_args)
    ours = ",".join(str(f) for f in getattr(cfg, "extension_dirs", ()))
    if ours:
        extra.append(f"--load-extension={ours}")
        if not gl_cfg.disable_extensions:
            LOG.warning(
                "[w%d] Extensions of your own replace the profile's bundled "
                "ones: Chromium keeps the last --load-extension, and the "
                "profile's come first.",
                worker_id,
            )
    if gl_cfg.disable_extensions and not any(
        a.startswith("--disable-extensions") for a in extra
    ):
        extra.append(
            f"--disable-extensions-except={ours}" if ours else "--disable-extensions"
        )

    if getattr(cfg, "allow_third_party_storage", False):
        extra += [
            "--disable-features=ThirdPartyStoragePartitioning",
            "--disable-third-party-cookie-blocking",
        ]
        LOG.info(
            "[w%d] Third-party storage left open for the nested Turnstile frame",
            worker_id,
        )

    if cfg.headless:
        extra += ["--headless=new", f"--window-size={cfg.window_size}"]

    options = {
        "token": gl_cfg.token,
        "profile_id": profile_id,
        "extra_params": extra,
    }
    if gl_cfg.fresh_session:
        options["writeCookiesFromServer"] = False
        options["restore_last_session"] = False

    gl = GoLogin(options)

    if gl_cfg.fresh_session:
        _clear_server_cookies(gl, profile_id, worker_id)

    LOG.info("[w%d] Starting GoLogin profile %s", worker_id, profile_id)
    LOG.info("[w%d] (a new Orbita version downloads on first use -- be patient)", worker_id)
    try:
        debugger_address = gl.start()
    except Exception as exc:
        raise GoLoginError(f"Could not start GoLogin profile {profile_id}: {exc}") from exc

    driver = None
    try:
        driver_path = resolve_chromedriver(gl.get_chromium_version(), gl_cfg.chromedriver_path)
        LOG.info(
            "[w%d] Orbita up on %s (chromedriver: %s)",
            worker_id, debugger_address, driver_path or "resolved by Selenium Manager",
        )
        driver = attach_driver(debugger_address, driver_path, cfg)
        _close_other_tabs(driver, worker_id)
        _size_window_to_screen(driver, cfg, worker_id)
        shim = SBShim(driver, timeout=cfg.page_timeout)
        stealth.apply(shim, cfg, "gologin")
        turnstile.install(shim, cfg)
        environment.audit(shim, cfg, worker_id)
        yield shim
    except GoLoginError:
        raise
    except Exception as exc:
        if driver is None:
            raise GoLoginError(
                f"Could not attach Selenium to Orbita at {debugger_address}: {exc}"
            ) from exc
        raise
    finally:
        _shutdown(
            driver,
            gl,
            keep_open=cfg.keep_open,
            worker_id=worker_id,
            fresh_session=gl_cfg.fresh_session,
        )


def _close_other_tabs(driver, worker_id: int) -> None:
    try:
        handles = driver.window_handles
    except Exception:
        return
    if len(handles) < 2:
        return

    LOG.info("[w%d] Closing %d tab(s) the profile came with", worker_id, len(handles) - 1)

    try:
        keep = driver.current_window_handle
    except Exception:
        keep = handles[-1]
    if keep not in handles:
        keep = handles[-1]
    for handle in handles:
        if handle == keep:
            continue
        try:
            driver.switch_to.window(handle)
            driver.close()
        except Exception as exc:
            LOG.debug("[w%d] Could not close a tab: %s", worker_id, exc)

    try:
        driver.switch_to.window(keep)
    except Exception as exc:
        LOG.warning("[w%d] Could not settle on a single tab: %s", worker_id, exc)


def _size_window_to_screen(driver, cfg: RunConfig, worker_id: int) -> None:
    if cfg.headless:
        return

    width = height = 0
    try:
        screen = driver.execute_script(
            "return {w: screen.availWidth, h: screen.availHeight,"
            " fw: screen.width, fh: screen.height};"
        ) or {}
        width = int(screen.get("w") or screen.get("fw") or 0)
        height = int(screen.get("h") or screen.get("fh") or 0)
    except Exception as exc:
        LOG.debug("[w%d] Could not read the profile's screen size: %s", worker_id, exc)

    if width < 800 or height < 600:
        try:
            width, height = (int(n) for n in cfg.window_size.split(","))
        except Exception:
            width, height = 1440, 1000

    display = real_input.display_size()
    if display:
        margin = 60
        width = min(width, display[0])
        height = min(height, max(600, display[1] - margin))

    try:
        driver.set_window_position(0, 0)
        driver.set_window_size(width, height)
        LOG.info("[w%d] Window sized to %dx%d", worker_id, width, height)
    except Exception as exc:
        LOG.warning(
            "[w%d] Could not size the window (%s). It may report zero outer "
            "dimensions, which reads as headless.", worker_id, exc,
        )


def _clear_server_cookies(gl: GoLogin, profile_id: str, worker_id: int) -> None:
    try:
        result = gl.clearCookies(profile_id) or {}
    except Exception as exc:
        LOG.warning("[w%d] Could not clear stored cookies: %s", worker_id, exc)
        return
    if result.get("status") != "success":
        LOG.warning("[w%d] GoLogin would not clear the stored cookies: %s", worker_id, result)


def _stop_without_saving(gl: GoLogin, worker_id: int) -> None:
    profile_path = getattr(gl, "profile_path", None)
    zip_path = getattr(gl, "profile_zip_path_upload", None)

    gl.local = True
    try:
        gl.stop()
    finally:
        for path in (zip_path,):
            try:
                if path and os.path.exists(path):
                    os.remove(path)
            except OSError as exc:
                LOG.debug("Could not remove %s: %s", path, exc)
        try:
            if profile_path and os.path.isdir(profile_path):
                shutil.rmtree(profile_path, ignore_errors=True)
        except OSError as exc:
            LOG.debug("Could not remove %s: %s", profile_path, exc)


def _shutdown(
    driver, gl: GoLogin, keep_open: bool, worker_id: int, fresh_session: bool = True
) -> None:
    if keep_open:
        if driver is not None:
            try:
                driver.service.stop()
            except Exception:
                pass
        LOG.info(
            "[w%d] Browser left running. Close it from the GoLogin app so the "
            "profile (cookies, session) is saved back to your account.",
            worker_id,
        )
        return

    if driver is not None:
        try:
            driver.close()
        except Exception:
            pass

    try:
        if fresh_session:
            LOG.info("[w%d] Stopping profile and discarding this run's session", worker_id)
            _stop_without_saving(gl, worker_id)
        else:
            LOG.info("[w%d] Stopping profile and syncing it back to GoLogin", worker_id)
            gl.stop()
    except Exception as exc:
        LOG.warning("[w%d] GoLogin stop() failed: %s", worker_id, exc)
