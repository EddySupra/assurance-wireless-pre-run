_driver_cache: dict[str, str | None] = {}
_driver_lock = threading.Lock()


def _latest_driver_for_major(major: str) -> str | None:
    """The newest chromedriver on a given Chrome major, e.g. 132.0.6834.159."""
    try:
        response = requests.get(CFT_LATEST_RELEASE.format(major=major), timeout=20)
        response.raise_for_status()
    except requests.RequestException as exc:
        LOG.warning("Could not look up a chromedriver for Chrome %s: %s", major, exc)
        return None

    version = response.text.strip()
    # A missing major returns an error page, not a version string.
    if not version.startswith(f"{major}.") or len(version.split(".")) != 4:
        return None
    return version


def resolve_chromedriver(chromium_version: str, explicit: str = "") -> str | None:
    """Path to a chromedriver matching Orbita, or None to let Selenium Manager decide."""
    if explicit:
        return explicit

    major = (chromium_version or "").split(".")[0]
    if not major.isdigit():
        LOG.warning("Could not read Orbita's version; falling back to Selenium Manager")
        return None

    # One lookup per Chrome major per process, not one per lead.
    with _driver_lock:
        if major in _driver_cache:
            return _driver_cache[major]

        path = None
        exact = _latest_driver_for_major(major)
        if exact is None:
            LOG.warning("No chromedriver published for Chrome %s; trying Selenium Manager", major)
        else:
            try:
                from webdriver_manager.chrome import ChromeDriverManager

                path = ChromeDriverManager(driver_version=exact).install()
            except Exception as exc:  # any failure here just means "try Selenium Manager"
                LOG.warning("webdriver-manager could not fetch chromedriver %s: %s", exact, exc)

        _driver_cache[major] = path
        return path


