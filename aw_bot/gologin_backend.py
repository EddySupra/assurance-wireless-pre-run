def attach_driver(debugger_address: str, driver_path: str | None, cfg: RunConfig):
    """Attach Selenium to the Orbita instance GoLogin already started."""
    options = Options()
    options.add_experimental_option("debuggerAddress", debugger_address)

    # "eager" returns the navigation at DOMContentLoaded instead of waiting on
    # every last subresource. Measured on these profiles, the start page is
    # interactive and fully usable at ~38s but keeps trickling in well past
    # that -- the residential proxy is simply slow, and the default "normal"
    # strategy turns a working page load into a timeout.
    options.page_load_strategy = "eager"

    # Chrome's console and network logs -- off unless asked for.
    #
    # These are not free. To serve them ChromeDriver turns on the CDP Runtime
    # and Network domains for the whole session, and a page can tell. The
    # standard check costs a page nothing: hand `console.log` an object with a
    # getter on `.stack`, and the getter fires only when something is
    # listening on Runtime. Cloudflare is known to probe for exactly that, and
    # it is one of the few signals that separates a browser being *driven*
    # from the same browser being used, whatever its fingerprint says.
    #
    # Which matters here, because the profile passes by hand and gets a
    # "Verify you are human" checkbox under automation. Worth being sure this
    # is not the reason before blaming the proxy.
    #
    # The irony is that these logs were turned on to diagnose "(600)" -- so
    # the diagnostic may have been feeding the problem it was measuring. Left
    # available behind --capture-logs for when that trade is worth making.
    if getattr(cfg, "capture_browser_logs", False):
        LOG.warning(
            "Browser/network logging is on. It enables the CDP Runtime and "
            "Network domains, which anti-bot scoring can detect -- use it to "
            "diagnose, not for production runs."
        )
        options.set_capability(
            "goog:loggingPrefs", {"browser": "ALL", "performance": "ALL"}
        )

    if driver_path:
        driver = webdriver.Chrome(service=Service(driver_path), options=options)
    else:
        driver = webdriver.Chrome(options=options)

    driver.set_page_load_timeout(cfg.page_timeout)
    return driver


@contextmanager
def gologin_session(cfg: RunConfig, profile_id: str, worker_id: int = 1):
    """Start `profile_id`, yield an sb-shaped handle, then stop and sync it back."""
    gl_cfg = cfg.gologin
    extra = list(gl_cfg.extra_args)
    if gl_cfg.disable_extensions and not any(
        a.startswith("--disable-extensions") for a in extra
    ):
        # See GoLoginConfig.disable_extensions: the bundled ad blocker blocks
        # Akamai's bot sensor, which is what gets these profiles refused.
        extra.append("--disable-extensions")

    if getattr(cfg, "allow_third_party_storage", False):
        # Turnstile runs three frames deep -- Cloudflare's frame inside the
        # Solix app's frame inside assurancewireless.com -- and a challenge
        # that cannot reach storage in its own frame cannot complete. Under
        # storage partitioning it gets a partitioned bucket rather than none,
        # which is usually fine; with third-party cookies actually blocked it
        # gets nothing, and fails with a `600***` code that this form reports
        # as its own "(600)".
        #
        # Opt-in rather than default, because it is a real change to how the
        # browser behaves and the storage check in aw_bot/environment.py will
        # say whether this profile needs it. Turn it on when that check warns.
        extra += [
            "--disable-features=ThirdPartyStoragePartitioning",
            "--disable-third-party-cookie-blocking",
        ]
        LOG.info(
            "[w%d] Third-party storage left open for the nested Turnstile frame",
            worker_id,
        )

    if cfg.headless:
        # Orbita is Chromium: the standard flags apply.
        extra += ["--headless=new", f"--window-size={cfg.window_size}"]

    options = {
        "token": gl_cfg.token,
        "profile_id": profile_id,
        "extra_params": extra,
    }
    if gl_cfg.fresh_session:
        # Start clean: don't pull the account's stored cookies into the profile
        # and don't reopen whatever the last run left on screen.
        options["writeCookiesFromServer"] = False
        options["restore_last_session"] = False

    gl = GoLogin(options)

    if gl_cfg.fresh_session:
        _clear_server_cookies(gl, profile_id, worker_id)

    LOG.info("[w%d] Starting GoLogin profile %s", worker_id, profile_id)
    LOG.info("[w%d] (a new Orbita version downloads on first use -- be patient)", worker_id)
    try:
        debugger_address = gl.start()
    except Exception as exc:
        raise GoLoginError(f"Could not start GoLogin profile {profile_id}: {exc}") from exc

    driver = None
    try:
        driver_path = resolve_chromedriver(gl.get_chromium_version(), gl_cfg.chromedriver_path)
        LOG.info(
            "[w%d] Orbita up on %s (chromedriver: %s)",
            worker_id, debugger_address, driver_path or "resolved by Selenium Manager",
        )
        driver = attach_driver(debugger_address, driver_path, cfg)
        _close_other_tabs(driver, worker_id)
        _size_window_to_screen(driver, cfg, worker_id)
        shim = SBShim(driver, timeout=cfg.page_timeout)
        # Artefact scrubbing only, by default: the profile's own fingerprint
        # is the whole point of running GoLogin. See aw_bot/stealth.py.
        stealth.apply(shim, cfg, "gologin")
        # Independent of the stealth switch: this only watches, and what it
        # watches is the one control that decides whether step 9 goes through.
        turnstile.install(shim, cfg)
        environment.audit(shim, cfg, worker_id)
        yield shim
    except GoLoginError:
        raise
    except Exception as exc:
        if driver is None:
            raise GoLoginError(
                f"Could not attach Selenium to Orbita at {debugger_address}: {exc}"
            ) from exc
        raise
    finally:
        _shutdown(
            driver,
            gl,
            keep_open=cfg.keep_open,
            worker_id=worker_id,
            fresh_session=gl_cfg.fresh_session,
        )


def _close_other_tabs(driver, worker_id: int) -> None:
    """Close the tabs the profile brought with it and keep one.

    Two reasons, and the second one is why this closes them rather than just
    saying they are there, which is all it used to do.

    Speed: every WebDriver command shares the browser with whatever else is
    loaded, and an ad-heavy page left open in another tab slows each one
    measurably -- field entry went from about three seconds to twenty-four
    with a tracker-laden page sitting in the background.

    Measurement: a tab that is not the foreground one has no window geometry
    to report. `window.outerWidth` comes back 0, which is exactly what a
    headless browser reports and what a window on a screen never does -- so
    the session looked headless to anything that checked, and the fingerprint
    audit flagged it. Orbita opens its own start page beside ours, so this was
    happening on every single run.

    The surviving tab is left as the active one, because that is the tab every
    step afterwards works in.
    """
    try:
        handles = driver.window_handles
    except Exception:
        return
    if len(handles) < 2:
        return

    LOG.info("[w%d] Closing %d tab(s) the profile came with", worker_id, len(handles) - 1)

    # Keep whichever tab the driver is already on rather than picking by
    # position: that is the one it attached to, and closing it would leave
    # every later command pointing at a window that no longer exists.
    try:
        keep = driver.current_window_handle
    except Exception:
        keep = handles[-1]
    if keep not in handles:
        keep = handles[-1]
    for handle in handles:
        if handle == keep:
            continue
        try:
            driver.switch_to.window(handle)
            driver.close()
        except Exception as exc:
            LOG.debug("[w%d] Could not close a tab: %s", worker_id, exc)

    try:
        driver.switch_to.window(keep)
    except Exception as exc:
        LOG.warning("[w%d] Could not settle on a single tab: %s", worker_id, exc)


def _size_window_to_screen(driver, cfg: RunConfig, worker_id: int) -> None:
    """Give the window real dimensions, and ones that fit the profile's screen.

    Two failures this prevents.

    A window that has never been sized can report zero outer dimensions --
    the headless signature above. Asking for a size realises the window and
    makes the honest answer a real one.

    And the size has to come from the profile rather than from a constant.
    Each generated fingerprint carries its own screen, so a fixed 1440x1000
    is larger than the screen on any profile that reports, say, 1366x768 --
    a browser window bigger than the monitor it claims to be on, which is a
    sharper contradiction than the one it was meant to fix. So the size is
    taken from `screen.availWidth/availHeight`: the dimensions a maximised
    window actually has on that machine, which is also the most ordinary
    thing for a window to be.
    """
    if cfg.headless:
        # Launched with an explicit --window-size already, and there is no
        # real window to place.
        return

    width = height = 0
    try:
        screen = driver.execute_script(
            "return {w: screen.availWidth, h: screen.availHeight,"
            " fw: screen.width, fh: screen.height};"
        ) or {}
        width = int(screen.get("w") or screen.get("fw") or 0)
        height = int(screen.get("h") or screen.get("fh") or 0)
    except Exception as exc:
        LOG.debug("[w%d] Could not read the profile's screen size: %s", worker_id, exc)

    if width < 800 or height < 600:
        # Unreadable or implausible: fall back to the configured size, which
        # is at least a real window rather than a zero-sized one.
        try:
            width, height = (int(n) for n in cfg.window_size.split(","))
        except Exception:
            width, height = 1440, 1000

    # Clamp to the monitor that actually exists.
    #
    # Everything above came from the browser, and on a GoLogin profile the
    # screen it reports belongs to its fingerprint rather than to this
    # machine. Sizing the window to a fingerprinted 1920x1080 on a smaller
    # physical display puts the bottom of the page below the bottom of the
    # screen -- which the synthetic path never notices, because it addresses
    # the page, and which breaks --real-input completely, because the real
    # mouse can only reach pixels that exist. Measured: the four step 6
    # fields all fell back to synthetic input, the lowest ones first.
    display = real_input.display_size()
    if display:
        margin = 60  # taskbar, and a window not quite filling the screen
        width = min(width, display[0])
        height = min(height, max(600, display[1] - margin))

    try:
        driver.set_window_position(0, 0)
        driver.set_window_size(width, height)
        LOG.info("[w%d] Window sized to %dx%d", worker_id, width, height)
    except Exception as exc:
        LOG.warning(
            "[w%d] Could not size the window (%s). It may report zero outer "
            "dimensions, which reads as headless.", worker_id, exc,
        )


def _clear_server_cookies(gl: GoLogin, profile_id: str, worker_id: int) -> None:
    """Drop the cookies GoLogin holds for this profile.

    Not belt-and-braces: earlier runs (before fresh_session existed, or any run
    that saved) may already have committed a block cookie to the account's copy
    of the profile, and start() would write it straight back into the browser.
    """
    try:
        result = gl.clearCookies(profile_id) or {}
    except Exception as exc:
        LOG.warning("[w%d] Could not clear stored cookies: %s", worker_id, exc)
        return
    if result.get("status") != "success":
        LOG.warning("[w%d] GoLogin would not clear the stored cookies: %s", worker_id, result)


def _stop_without_saving(gl: GoLogin, worker_id: int) -> None:
    """Stop the browser and discard what it did, instead of saving it back.

    GoLogin's stop() ends with commitProfile(), which uploads the browser's
    state to the account. Setting `local` is the switch stop() itself checks to
    skip that -- it also skips the temp-file cleanup that follows, so we do
    that part here.
    """
    profile_path = getattr(gl, "profile_path", None)
    zip_path = getattr(gl, "profile_zip_path_upload", None)

    gl.local = True
    try:
        gl.stop()
    finally:
        for path in (zip_path,):
            try:
                if path and os.path.exists(path):
                    os.remove(path)
            except OSError as exc:
                LOG.debug("Could not remove %s: %s", path, exc)
        try:
            if profile_path and os.path.isdir(profile_path):
                shutil.rmtree(profile_path, ignore_errors=True)
        except OSError as exc:
            LOG.debug("Could not remove %s: %s", profile_path, exc)


def _shutdown(
    driver, gl: GoLogin, keep_open: bool, worker_id: int, fresh_session: bool = True
) -> None:
    if keep_open:
        if driver is not None:
            # Stop chromedriver but not Orbita: driver.quit() would close the
            # browser out from under the profile.
            try:
                driver.service.stop()
            except Exception:
                pass
        LOG.info(
            "[w%d] Browser left running. Close it from the GoLogin app so the "
            "profile (cookies, session) is saved back to your account.",
            worker_id,
        )
        return

    if driver is not None:
        # close(), not quit(): gl.stop() is what shuts Orbita down and syncs the
        # profile back, and quit() would pull the browser out from under it.
        try:
            driver.close()
        except Exception:
            pass

    try:
        if fresh_session:
            LOG.info("[w%d] Stopping profile and discarding this run's session", worker_id)
            _stop_without_saving(gl, worker_id)
        else:
            LOG.info("[w%d] Stopping profile and syncing it back to GoLogin", worker_id)
            gl.stop()
    except Exception as exc:
        LOG.warning("[w%d] GoLogin stop() failed: %s", worker_id, exc)
