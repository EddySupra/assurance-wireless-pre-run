"""Starting browsers as GoLogin (Orbita) profiles.

A GoLogin profile carries its own fingerprint, proxy, cookies and local
storage, which is what replaces UC mode here: the anti-bot layer sees a browser
identity that GoLogin maintains, not a patched chromedriver on this machine.

GoLogin starts Orbita itself and hands back a DevTools debugger address; we
attach Selenium to that, then wrap the driver in SBShim so the existing steps
keep working unchanged.

Ported from the standalone gologin_nav.py, including its chromedriver pinning:
Orbita reports versions like "132.1.2.73", which is not a real chromedriver
release, so only the major version is worth matching -- and it has to be
widened to a real four-part version first, because webdriver-manager handed a
bare major quietly installs a different one that then refuses to attach.
"""

