def create_disposable_profile(cfg: RunConfig, worker_id: int = 1) -> tuple[str, str]:
    """Build a throwaway GoLogin profile with its own fingerprint and proxy.

    Returns (profile_id, description).

    The fingerprint comes from GoLogin's own generator rather than anything
    assembled here, and that is deliberate: it returns a *coherent* identity
    where the OS, user agent, screen, GPU, font list and timezone were chosen
    to agree with each other. Hand-picking a few of those values is how you
    end up with a browser claiming one machine while the rest of it says
    another, which is more visible than an ordinary fingerprint, not less.
    """
    gl_cfg = cfg.gologin
    gl = GoLogin({"token": gl_cfg.token, "profile_id": None})

    os_choice = _pick_os(gl_cfg.profile_os)
    name = f"aw-{worker_id}-{random.randint(100000, 999999)}"

    try:
        created = gl.createProfileRandomFingerprint({"os": os_choice, "name": name})
    except Exception as exc:
        raise GoLoginError(f"Could not create a GoLogin profile: {exc}") from exc

    profile_id = _created_id(created)
    if not profile_id:
        raise GoLoginError(f"GoLogin did not return a profile id (got {created!r})")

    LOG.info("[w%d] Created profile %s (%s, os=%s)", worker_id, profile_id, name, os_choice)

    _freshen_user_agent(gl, profile_id, worker_id)

    try:
        gl.addGologinProxyToProfile(
            profile_id, gl_cfg.proxy_country, gl_cfg.proxy_type or ""
        )
        LOG.info(
            "[w%d] Attached a %s %s proxy",
            worker_id, gl_cfg.proxy_country, gl_cfg.proxy_type or "auto-selected",
        )
    except Exception as exc:
        # A profile with no proxy would go out on this machine's own IP --
        # which the enrollment host refuses outright, and which would also
        # put the operator's home connection in front of the site. Delete it
        # and fail rather than quietly running without the proxy.
        delete_profile(gl_cfg.token, profile_id, worker_id)
        raise GoLoginError(
            f"Could not attach a proxy to the new profile ({exc}). "
            f"Check the account's {gl_cfg.proxy_type or 'proxy'} traffic balance."
        ) from exc

    # After the proxy, because what it fixes depends on the exit being known.
    _match_profile_to_proxy(gl, profile_id, worker_id)

    return profile_id, f"{name} ({os_choice})"


# Roughly the share of US desktop Chrome each platform actually has. An even
# split between Windows and macOS is not a neutral choice -- it is a choice
# that makes every other profile a Mac, which is about three times as many as
# the real population has. The point of a generated fingerprint is to be
# unremarkable, and "unremarkable" is a distribution, not a coin flip.
_OS_WEIGHTS = {"win": 78, "mac": 18, "lin": 4}


def _pick_os(allowed) -> str:
    """One OS from `allowed`, drawn the way the real population is shaped."""
    options = tuple(allowed or ("win",))
    weights = [_OS_WEIGHTS.get(name, 1) for name in options]
    return random.choices(options, weights=weights, k=1)[0]


def _freshen_user_agent(gl, profile_id: str, worker_id: int) -> None:
    """Move the profile's user agent up to the browser version it will run as.

    GoLogin's generator picks a user agent from its own pool, and that pool
    lags the Orbita build the profile is actually launched with. The result is
    a browser whose UA claims one Chrome while everything measured underneath
    it -- the client-hint brand list, the JS engine's behaviour, the TLS and
    HTTP/2 fingerprints -- belongs to another. That disagreement is worth more
    to anything checking than the UA string itself, because a plain UA is
    shared with millions of people and a contradiction is shared with almost
    nobody.

    Best-effort: a profile with a slightly old UA is still usable, so a
    failure here is logged and the lead goes ahead.
    """
    try:
        gl.updateUserAgentToLatestBrowser([profile_id])
        LOG.info("[w%d] User agent matched to the current browser build", worker_id)
    except Exception as exc:
        LOG.warning(
            "[w%d] Could not update the profile's user agent (%s). The profile "
            "still works; its UA may name an older Chrome than Orbita runs.",
            worker_id, exc,
        )


def _match_profile_to_proxy(gl, profile_id: str, worker_id: int) -> None:
    """Stop the profile contradicting the proxy it goes out through.

    Reads the profile and only changes what is actually wrong, rather than
    writing a set of values over the top -- the generated fingerprint is
    coherent and worth leaving alone.

    The one that matters is WebRTC. In `real` mode the browser answers STUN
    with the machine's true address, so a page can read the home IP straight
    past the proxy: the site sees a residential exit in California and a
    WebRTC candidate from wherever this computer is. Nothing else in the
    fingerprint matters if that is on.
    """
    try:
        gl.setProfileId(profile_id)
        profile = gl.getProfile(profile_id) or {}
    except Exception as exc:
        LOG.debug("[w%d] Could not read the new profile back: %s", worker_id, exc)
        return

    changes: dict = {}

    webrtc = dict(profile.get("webRTC") or {})
    if webrtc.get("mode") == "real" or webrtc.get("fillBasedOnIp") is False:
        webrtc["mode"] = "alerted"        # GoLogin's name for "masked"
        webrtc["fillBasedOnIp"] = True    # follow the proxy exit, not this machine
        changes["webRTC"] = webrtc

    # The timezone should come from the exit IP too. A browser in
    # America/Los_Angeles behind a New York exit is the same kind of
    # contradiction, and GoLogin will derive it if asked.
    timezone = dict(profile.get("timezone") or {})
    if timezone.get("fillBasedOnIp") is False:
        timezone["fillBasedOnIp"] = True
        changes["timezone"] = timezone

    if not changes:
        LOG.debug("[w%d] Profile already agrees with its proxy", worker_id)
        return

    try:
        gl.update({"id": profile_id, **changes})
        LOG.info(
            "[w%d] Pointed %s at the proxy exit", worker_id, ", ".join(changes)
        )
    except Exception as exc:
        LOG.warning(
            "[w%d] Could not align the profile with its proxy (%s): %s",
            worker_id, ", ".join(changes), exc,
        )


def _created_id(created) -> str:
    """The profile id out of whatever shape the API answered with."""
    if isinstance(created, str):
        return created
    if isinstance(created, dict):
        for key in ("id", "_id", "profileId", "browserId"):
            value = created.get(key)
            if value:
                return str(value)
    return ""


def delete_profile(token: str, profile_id: str, worker_id: int = 1) -> bool:
    """Remove a disposable profile. Never raises: it is cleanup.

    Returns whether it went, so a bulk tidy-up can report an honest count.
    """
    try:
        GoLogin({"token": token, "profile_id": profile_id}).delete(profile_id)
        LOG.info("[w%d] Deleted profile %s", worker_id, profile_id)
        return True
    except Exception as exc:
        # Worth saying: these accumulate against the account's profile limit,
        # and a run that leaks them will eventually fail to create more.
        LOG.warning(
            "[w%d] Could not delete profile %s: %s -- remove it at app.gologin.com",
            worker_id, profile_id, exc,
        )
        return False


